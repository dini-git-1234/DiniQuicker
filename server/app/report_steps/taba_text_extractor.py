async def generate_property_report(
    file_paths: List[str],
    existing_rights_table: Dict[str, Any] | None = None,
) -> Dict[str, Any]:
    """
    מחזיר טבלת זכויות בניה במבנה {"headers": [...], "rows": [[...], ...]}
    על בסיס ניתוח קבצי התב\"ע באמצעות Gemini.
    """
    prompt = SYSTEM_PROMPT_TEMPLATE

    if existing_rights_table:
        # נמסור למודל את טבלת הזכויות החלקית כדי שימשיך ממנה
        try:
            existing_json = json.dumps(existing_rights_table, ensure_ascii=False)
        except TypeError:
            existing_json = str(existing_rights_table)

        prompt += f"""

בנוסף למסמכי התב\"ע, קיבלת מהמערכת טבלת זכויות חלקית שכבר הופקה ממקור אחר (למשל אתר העירייה).
הטבלה החלקית הזו בקידוד JSON היא:
{existing_json}

הנחיות נוספות:
- התייחס לזכויות שמופיעות בטבלה החלקית כנתונים קיימים ואמינים, כולל מספר/שם תכנית אם מופיע שם.
- אל תחזור על אותן זכויות בלי צורך, אלא השתמש בהן כבסיס.
- השלם על בסיס קבצי התב\"ע את הזכויות/הפרטים החסרים (למשל פרמטרים שלא מופיעים בטבלה החלקית).
- כאשר אתה ממלא את השדה "source_plan" עבור כל פרמטר:
  * השתמש **רק** במספר/שם תכנית תב\"ע (מתוך המסמכים או מתוך הטבלה החלקית) ולא בטקסט כללי.
  * אל תכתוב שם ביטויים כמו "טבלה חלקית", "טבלת זכויות חלקית" או כל התייחסות לטבלת הביניים כמקור.
  * אם אין תכנית מקור ברורה, השאר את השדה ריק או כתוב "לא ברור במסמכים".
- הפלט הסופי חייב להיות אך ורק במבנה ה-JSON שהוגדר למעלה (רשימת פרמטרים סטנדרטיים), לא טבלת המקור.
"""

    prompt = f"{prompt}\n\nאנא נתח את המסמכים המצורפים והחזר אך ורק JSON במבנה שהוגדר."

    raw_response = await ask_gemini_with_search(
        prompt=prompt,
        model_name="gemini-2.0-flash",
        images=file_paths,
        use_search=False,
    )

    # ניסיון לפענח JSON (כולל ניקוי אפשרי של ```json ... ``` אם המודל הוסיף)
    text = raw_response.strip()
    if text.startswith("```"):
        # הסרה של גדרות קוד אם קיימות
        text = text.strip("`")
        if text.lower().startswith("json"):
            text = text[4:]
        text = text.strip()

    try:
        parsed = json.loads(text)
    except json.JSONDecodeError:
        # במקרה כשל – נחזיר טבלה ריקה עם כותרות בסיסיות כדי לא להפיל את הזרימה
        return {
            "headers": ["פרמטר", "ערך", "תכנית מקור", "הערות"],
            "rows": [],
        }

    if not isinstance(parsed, list):
        return {
            "headers": ["פרמטר", "ערך", "תכנית מקור", "הערות"],
            "rows": [],
        }

    headers = ["פרמטר", "ערך", "תכנית מקור", "הערות"]
    rows: List[List[str]] = []

    for item in parsed:
        if not isinstance(item, dict):
            continue
        parameter = str(item.get("parameter", "") or "")
        value = str(item.get("value", "") or "")
        source_plan = str(item.get("source_plan", "") or "")
        notes = str(item.get("notes", "") or "")
        rows.append([parameter, value, source_plan, notes])

    return {
        "headers": headers,
        "rows": rows,
    }

